package bench

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"maps"
	"slices"
	"strings"
	"time"
)

// The markers around the generated part of docs/BENCHMARKS.md; the text
// outside them is written by hand and survives regeneration.
const (
	GeneratedBegin = "<!-- generated by eacp-bench report: do not edit -->"
	GeneratedEnd   = "<!-- end generated -->"
)

// Caveats is printed with every report (MASTER_PLAN §105).
const Caveats = "Measured on one development machine (details above). The ERP and the LLM are local fakes that " +
	"answer immediately, so External and LLM figures are the fakes' own time, not a real system's. Overhead is " +
	"end-to-end minus governance minus external: the control plane's own time. One tenant. These figures are not a " +
	"capacity claim for production hardware."

// Input is one results file: its name and its exact bytes.
type Input struct {
	Name string
	Raw  []byte
}

// Splice replaces the generated block in doc (markers included) with
// block, or returns block alone when doc has none.
func Splice(doc, block string) string {
	i := strings.Index(doc, GeneratedBegin)
	j := strings.Index(doc, GeneratedEnd)
	if i < 0 || j < i {
		return block + "\n"
	}
	return doc[:i] + block + doc[j+len(GeneratedEnd):]
}

type parsed struct {
	Input
	r Results
}

// Report renders results files as the generated markdown block. The output
// depends only on the inputs' contents, never on their order.
func Report(inputs []Input) (string, error) {
	if len(inputs) == 0 {
		return "", fmt.Errorf("no results files")
	}
	var all []parsed
	for _, in := range inputs {
		var r Results
		if err := json.Unmarshal(in.Raw, &r); err != nil {
			return "", fmt.Errorf("%s: %w", in.Name, err)
		}
		if r.Schema != SchemaVersion {
			return "", fmt.Errorf("%s: schema %d, want %d", in.Name, r.Schema, SchemaVersion)
		}
		all = append(all, parsed{in, r})
	}
	slices.SortFunc(all, func(a, b parsed) int { return strings.Compare(a.r.PDP+a.Name, b.r.PDP+b.Name) })

	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	latest := all[0].r
	for _, p := range all {
		if p.r.StartedAt.After(latest.StartedAt) {
			latest = p.r
		}
	}
	m := latest.Machine
	w("%s\n\n", GeneratedBegin)
	w("Generated by `eacp-bench report` from the raw results below; `scripts/bench.sh` reproduces them.\n\n")
	w("| | |\n|---|---|\n")
	w("| Run | %s |\n", latest.StartedAt.UTC().Format(time.DateOnly))
	dirty := ""
	if latest.Dirty {
		dirty = " (uncommitted changes)"
	}
	w("| Commit | `%s`%s |\n", latest.GitSHA, dirty)
	w("| Host | %s, %d cores, %s RAM |\n", m.HostCPU, m.HostCores, gib(m.HostMemBytes))
	w("| Docker | %d CPUs, %s memory (%s) |\n", m.DockerCPUs, gib(m.DockerMemBytes), m.Docker)
	w("| Software | %s, %s, PostgreSQL %s |\n\n", m.OS, m.Go, m.Postgres)
	w("Raw results (SHA-256):\n\n")
	for _, p := range all {
		sum := sha256.Sum256(p.Raw)
		w("- `%s` (%s): `%s`\n", p.Name, p.r.PDP, hex.EncodeToString(sum[:]))
	}
	w("\n> %s\n\n", Caveats)

	w("## Configuration\n\n| PDP | Setting | Bench value | Default |\n|---|---|---|---|\n")
	for _, p := range all {
		for _, o := range p.r.Overrides {
			w("| %s | `%s` | %s | %s |\n", p.r.PDP, o.Name, o.Value, o.Default)
		}
		for _, k := range slices.Sorted(maps.Keys(p.r.Flags)) {
			w("| %s | flag `%s` | %s | |\n", p.r.PDP, k, p.r.Flags[k])
		}
	}

	levels := map[int]bool{}
	for _, p := range all {
		for _, l := range p.r.Levels {
			levels[l.Agents] = true
		}
	}
	ns := slices.Sorted(maps.Keys(levels))
	w("\n## Maximum sustainable rate (requests/s)\n\nThe highest rung of the rate ladder that was neither saturated nor " +
		"incomplete, and the rung that failed: the true limit lies between them.\n\n| PDP |")
	for _, n := range ns {
		w(" %d agents |", n)
	}
	w("\n|---|%s\n", strings.Repeat("---|", len(ns)))
	for _, p := range all {
		w("| %s |", p.r.PDP)
		for _, n := range ns {
			v, ok := p.r.MaxSustainable[n]
			if !ok {
				w(" not run |")
				continue
			}
			var steps []Step
			for _, l := range p.r.Levels {
				if l.Agents == n {
					steps = l.Steps
				}
			}
			w(" %s |", maxCell(steps, v))
		}
		w("\n")
	}

	w("\n## Setup\n\n| PDP | Agents | Seconds |\n|---|---|---|\n")
	for _, p := range all {
		for _, s := range p.r.Setup {
			w("| %s | %d | %.1f |\n", p.r.PDP, s.Agents, s.Seconds)
		}
	}

	for _, p := range all {
		w("\n## Action path: %s PDP\n\n", p.r.PDP)
		w("Latencies in ms as P50 / P95 / P99. Offered/s counts every request; 5%% of them replay an earlier " +
			"idempotency key and create no action, so Completed/s is judged against the other 95%%.\n\n")
		w("| Agents | Offered/s | Admission | Governance | Queue wait | Lease | External | Overhead | End-to-end | " +
			"Idempotency | Budget reserve (mean) | Completed/s | Errors | 429 | Terminal | Status |\n")
		w("|%s\n", strings.Repeat("---|", 16))
		for _, l := range p.r.Levels {
			for _, s := range l.Steps {
				w("%s\n", actionRow(l.Agents, s))
			}
		}
		w("\n### Resources: %s PDP\n\n", p.r.PDP)
		w("CPU as mean / max %% of one core, then peak memory.\n\n| Agents | Offered/s |")
		services := append(slices.Clone(KnownServices), "eacp-bench")
		for _, svc := range services {
			w(" %s |", svc)
		}
		w("\n|%s\n", strings.Repeat("---|", len(services)+2))
		for _, l := range p.r.Levels {
			for _, s := range l.Steps {
				w("| %d | %s |", l.Agents, num(s.Offered))
				for _, svc := range services {
					r, ok := s.Containers[svc]
					if !ok {
						r = Resource{NA: "not sampled"}
					}
					w(" %s |", resourceCell(r))
				}
				w("\n")
			}
		}
		w("\n| Agents | Offered/s | DB commits/s | DB cache hit | DB max active | DB max lock waits | "+
			"NATS msgs in/s | NATS msgs out/s | Duplicate keys | Replays answered with another action |\n|%s\n",
			strings.Repeat("---|", 10))
		for _, l := range p.r.Levels {
			for _, s := range l.Steps {
				w("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", l.Agents, num(s.Offered),
					ratesCell(s.DB, "commits_per_s"), ratesCell(s.DB, "cache_hit_ratio"), ratesCell(s.DB, "max_active"),
					ratesCell(s.DB, "max_lock_waits"), ratesCell(s.NATS, "in_msgs_per_s"),
					ratesCell(s.NATS, "out_msgs_per_s"), dupCell(s), replayCell(s))
			}
		}
		if len(p.r.LLM) > 0 {
			w("\n## LLM gateway: %s run\n\n", p.r.PDP)
			w("Against a fake provider that answers immediately: this is the gateway's own overhead, not an LLM's " +
				"latency. Latencies in ms as P50 / P95 / P99.\n\n")
			w("| Offered/s | Client | Ledger admit to settle | Completed/s | Errors | 429 | Status |\n|%s\n",
				strings.Repeat("---|", 7))
			for _, s := range p.r.LLM {
				w("| %s | %s | %s | %.1f | %d | %d | %s |\n", num(s.Offered), summaryCell(s.LLMClient),
					summaryCell(s.LLMLedger), s.CompletedThroughput, s.Errors, s.Throttled, statusCell(s))
			}
		}
	}
	w("\n%s", GeneratedEnd)
	return b.String(), nil
}

func summaryCell(s Summary) string {
	if s.Count == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%.1f / %.1f / %.1f", s.P50Ms, s.P95Ms, s.P99Ms)
}

func budgetCell(s Step) string {
	if s.BudgetReserveMeanMs == nil {
		why := s.NA["budget_reserve"]
		if why == "" {
			why = "not measured"
		}
		return "n/a (" + why + ")"
	}
	return fmt.Sprintf("%.3f ms", *s.BudgetReserveMeanMs)
}

func resourceCell(r Resource) string {
	if r.NA != "" {
		return "n/a (" + r.NA + ")"
	}
	return fmt.Sprintf("%.1f / %.1f%%, %s", r.MeanCPU, r.MaxCPU, mib(r.MaxMemBytes))
}

func ratesCell(r Rates, key string) string {
	if r.NA != "" {
		return "n/a (" + r.NA + ")"
	}
	v, ok := r.PerSecond[key]
	if !ok {
		return "n/a"
	}
	if key == "cache_hit_ratio" {
		return fmt.Sprintf("%.3f", v)
	}
	return num(v)
}

func terminalCell(s Step) string {
	var parts []string
	for _, k := range slices.Sorted(maps.Keys(s.Terminal)) {
		parts = append(parts, fmt.Sprintf("%s %d", k, s.Terminal[k]))
	}
	if s.Open > 0 {
		parts = append(parts, fmt.Sprintf("open %d", s.Open))
	}
	if len(parts) == 0 {
		return "none"
	}
	return strings.Join(parts, ", ")
}

// stepFailed is why a step's figures could not be collected, or "".
func stepFailed(s Step) string {
	for _, k := range []string{"database", "window", "drain", "timelines"} {
		if why, ok := s.NA[k]; ok {
			return k + ": " + why
		}
	}
	return ""
}

// actionRow is one row of an action-path table; a failed step shows n/a in
// every measured cell and why in its status.
func actionRow(agents int, s Step) string {
	if why := stepFailed(s); why != "" {
		return fmt.Sprintf("| %d | %s |%s failed (%s) |", agents, num(s.Offered), strings.Repeat(" n/a |", 13), why)
	}
	return fmt.Sprintf("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %.1f | %d | %d | %s | %s |",
		agents, num(s.Offered), summaryCell(s.Admission), summaryCell(s.Governance), summaryCell(s.QueueWait),
		summaryCell(s.Lease), summaryCell(s.External), summaryCell(s.Overhead), summaryCell(s.EndToEnd),
		summaryCell(s.Idempotency), budgetCell(s), s.CompletedThroughput, s.Errors, s.Throttled, terminalCell(s),
		statusCell(s))
}

func statusCell(s Step) string {
	var out string
	switch {
	case s.Incomplete && s.Open > 0:
		out = fmt.Sprintf("incomplete: %d still open; latencies cover finished actions only", s.Open)
	case s.Incomplete:
		out = "incomplete"
	case len(s.Saturated) > 0:
		out = "saturated (" + strings.Join(s.Saturated, ", ") + ")"
	default:
		out = "ok"
	}
	if s.PreexistingOpen > 0 {
		out += fmt.Sprintf("; began with %d earlier actions open", s.PreexistingOpen)
	}
	return out
}

// maxCell is a level's maximum sustainable rate and the rung that failed.
func maxCell(steps []Step, best float64) string {
	v := "none"
	if best > 0 {
		v = num(best)
	}
	for _, s := range steps {
		switch {
		case s.Incomplete:
			return fmt.Sprintf("%s (incomplete at %s)", v, num(s.Offered))
		case len(s.Saturated) > 0:
			return fmt.Sprintf("%s (saturated at %s)", v, num(s.Offered))
		}
	}
	return v + " (highest rung)"
}

func dupCell(s Step) string {
	if why, ok := s.NA["duplicate_keys"]; ok {
		return "n/a (" + why + ")"
	}
	return fmt.Sprint(s.DuplicateKeys)
}

func replayCell(s Step) string {
	if s.ReplayMissing > 0 {
		return fmt.Sprintf("%d (%d without an action id)", s.ReplayMismatched, s.ReplayMissing)
	}
	return fmt.Sprint(s.ReplayMismatched)
}

// num prints integers without a fraction and others with one decimal.
func num(v float64) string {
	if v == float64(int64(v)) {
		return fmt.Sprintf("%d", int64(v))
	}
	return fmt.Sprintf("%.1f", v)
}

func gib(b int64) string { return fmt.Sprintf("%.1f GiB", float64(b)/(1<<30)) }
func mib(b int64) string { return fmt.Sprintf("%.0f MiB", float64(b)/(1<<20)) }
